/*
 * st_comm.c
 *
 *  See st_comm.h.
 */
#include <string.h>

#include "st_comm.h"
#include "st_hw_config.h"

#define RX_BUFFER_LENGTH	512		// power of 2

extern UART_HandleTypeDef hcom_uart[];

/** Private variables */
static volatile uint8_t rxBuffer[RX_BUFFER_LENGTH];
static volatile uint16_t rxHead;	// written by the ISR
static volatile uint16_t rxTail;	// written by the main loop
static uint16_t lineLength;
static uint8_t lineOverflow;


void stCommInit(void){
	rxHead = 0;
	rxTail = 0;
	lineLength = 0;
	lineOverflow = 0;
	COM1_UART->CR1 |= USART_CR1_RXNEIE_RXFNEIE;
	HAL_NVIC_SetPriority(USART1_IRQn, ST_COMM_IRQ_PRIO, 0);
	HAL_NVIC_EnableIRQ(USART1_IRQn);
}


int8_t stCommReadLine(char *line, uint16_t length){
	while (rxTail != rxHead){
		char c = (char)rxBuffer[rxTail];
		rxTail = (rxTail + 1U) & (RX_BUFFER_LENGTH - 1U);

		if ((c == '\r') || (c == '\n')){
			if (lineOverflow){
				lineOverflow = 0;
				lineLength = 0;
				return -1;
			}
			if (lineLength == 0)
				continue;	// empty line or second char of "\r\n"
			line[lineLength] = '\0';
			lineLength = 0;
			return 1;
		}
		if (lineLength < (length - 1U))
			line[lineLength++] = c;
		else
			lineOverflow = 1;
	}
	return 0;
}


void stCommWriteLine(const char *text){
	HAL_UART_Transmit(&hcom_uart[COM1], (const uint8_t *)text, (uint16_t)strlen(text), 100);
	HAL_UART_Transmit(&hcom_uart[COM1], (const uint8_t *)"\r\n", 2, 100);
}


/**
 * USART1 interrupt (ST-LINK virtual COM port). Not generated by CubeMX
 * because the port is owned by the BSP.
 */
void USART1_IRQHandler(void){
	uint32_t isr = COM1_UART->ISR;

	if ((isr & (USART_ISR_ORE | USART_ISR_FE | USART_ISR_NE | USART_ISR_PE)) != 0U)
		COM1_UART->ICR = USART_ICR_ORECF | USART_ICR_FECF | USART_ICR_NECF | USART_ICR_PECF;

	while ((COM1_UART->ISR & USART_ISR_RXNE_RXFNE) != 0U){
		uint8_t c = (uint8_t)COM1_UART->RDR;
		uint16_t next = (rxHead + 1U) & (RX_BUFFER_LENGTH - 1U);
		if (next != rxTail){		// drop the character if the buffer is full
			rxBuffer[rxHead] = c;
			rxHead = next;
		}
	}
}
